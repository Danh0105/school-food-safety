 await observer.getByRole('navigation',{name:'Phân hệ quản lý kho'}).getByRole('button',{name:'Nhập kho',exact:true}).click()
 await page.getByRole('button',{name:'Thêm phiếu nhập',exact:true}).click()
 const form=page.getByRole('dialog',{name:'Thêm mới phiếu nhập kho'})
 await choose(form.getByLabel('Nhà cung cấp',{exact:true}),'supplier-demo-trace')
 await choose(form.getByLabel('Tên hàng hóa dòng 1'),'product-2')
 await form.getByLabel('Số lô dòng 1').fill('DEMO-LOCAL-LOT-01')
