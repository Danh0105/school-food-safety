 await form.getByLabel('Đơn giá dòng 1').fill('12000')
 await form.getByRole('button',{name:'Lưu phiếu nhập',exact:true}).click()
 await expect(form).toBeHidden()
 await expect(observer.locator('tbody tr').filter({hasText:'NK000003'})).toBeVisible()
