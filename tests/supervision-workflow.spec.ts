import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { readFile } from 'node:fs/promises'

async function role(page:Page, name:string) {
  await page.getByRole('button',{name:'Chuyển không gian làm việc'}).click()
  await page.getByRole('button',{name,exact:true}).click()
  await page.locator('.sidebar').getByRole('link',{name:'Giám sát & an toàn',exact:true}).click()
}
const evidence = ['public/meal-ready-demo.webp','public/meal-demo.jpg','public/images/canteen/view-1.jpg','public/images/canteen/view-2.jpg']
async function record(page:Page, action:string, time:string, image:string, quantity=485, note='') {
  await page.getByRole('button',{name:action,exact:true}).click()
  const form=page.getByRole('dialog')
  await form.getByLabel('Thời điểm thực tế').fill(`2026-10-17T${time}`)
  await form.getByRole('spinbutton').fill(String(quantity))
  await form.getByLabel('Ảnh thực tế cho mốc').setInputFiles(image)
  await form.getByLabel('Ghi chú / lý do chênh lệch').fill(note)
  if(await form.getByRole('checkbox').count())await form.getByRole('checkbox').check()
  await form.getByRole('button',{name:/^(Lưu mốc và ảnh|Xác nhận mốc và ảnh)$/}).click()
}

