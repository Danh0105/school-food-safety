  await record(page,'Đã xuất bếp','09:30',evidence[0]!)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.admin-timeline')).toContainText('Số suất ghi nhận: 485')

  const receiver=await context.newPage()
  await receiver.emulateMedia({reducedMotion:'reduce'})
  await receiver.goto('/')
  await role(receiver,'Ban Giám hiệu')
  await receiver.getByRole('button',{name:'Xác nhận mốc đã xuất bếp',exact:true}).click()
  await expect(receiver.getByRole('dialog')).toContainText('09:30')
  await receiver.screenshot({path:'docs/screenshots/supervision-confirm-popup.png'})
  await receiver.setViewportSize({width:390,height:844})
  expect(await receiver.getByRole('dialog').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
  const popupA11y=await new AxeBuilder({page:receiver}).withTags(['wcag2a','wcag2aa']).analyze()
  expect(popupA11y.violations.map(v=>v.id)).toEqual([])
  await receiver.screenshot({path:'docs/screenshots/supervision-confirm-popup-390.png'})
  await receiver.setViewportSize({width:1440,height:1000})
  await receiver.getByRole('dialog').getByRole('button',{name:'Hủy',exact:true}).click()
  await expect(receiver.getByRole('button',{name:'Xác nhận mốc đã xuất bếp',exact:true})).toBeVisible()
  await receiver.getByRole('button',{name:'Xác nhận mốc đã xuất bếp',exact:true}).click()
  await receiver.getByRole('dialog').getByRole('checkbox').check()
  await receiver.getByRole('dialog').getByLabel('Ghi chú xác nhận').fill('Đã đối chiếu giờ xuất và ảnh bàn giao')
  await receiver.getByRole('dialog').getByRole('button',{name:'Lưu xác nhận',exact:true}).click()
  await expect(receiver.getByRole('button',{name:'Xác nhận đến trường',exact:true})).toBeVisible()
  await record(receiver,'Xác nhận đến trường','10:00',evidence[0]!,480)
  await expect(receiver.getByRole('alert')).toContainText('Ảnh này đã được dùng')
  await receiver.getByRole('dialog').getByLabel('Ảnh thực tế cho mốc').setInputFiles(evidence[1]!)
  await receiver.getByRole('dialog').getByRole('button',{name:'Xác nhận mốc và ảnh'}).click()
  await expect(receiver.getByRole('alert')).toContainText('lý do chênh lệch')
  await receiver.getByRole('dialog').getByLabel('Ghi chú / lý do chênh lệch').fill('Thiếu 5 suất khi đối chiếu bàn giao DEMO')
  await receiver.getByRole('dialog').getByRole('button',{name:'Xác nhận mốc và ảnh'}).click()
  await expect(receiver.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.admin-timeline')).toContainText('Chênh lệch -5 suất')
  await expect(page.getByRole('button',{name:'Đã đến trường',exact:true})).toHaveCount(0)
  await receiver.close()

  await role(page,'Ban Giám hiệu')
  await record(page,'Xác nhận ra món','10:20',evidence[2]!,480)
  await record(page,'Xác nhận sẵn sàng phục vụ','10:40',evidence[3]!,480)
  await expect(page.locator('.admin-timeline img')).toHaveCount(4)
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('demo-admin-meals')??'[]').find((m:{schoolId:string})=>m.schoolId==='an-phu'))
  expect(saved.events.map((event:{status:string})=>event.status)).toEqual(['DISPATCHED','ARRIVED','PLATED','READY'])
  expect(saved.version).toBe(5)
  expect(new Set(saved.events.map((event:{idempotencyKey:string})=>event.idempotencyKey)).size).toBe(4)

  await role(page,'Phụ huynh')
  await expect(page.locator('.admin-timeline')).toHaveCount(0)
  await expect(page.getByText('Ảnh đã được xác nhận công khai (DEMO)',{exact:true})).toBeVisible()
  await role(page,'Ban Giám hiệu')
